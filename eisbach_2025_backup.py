# Helper function to plot a forecast
def plot_forecast(df_forecast, label, color, plot_end_time=None):
    if plot_end_time is not None:
        df_forecast = df_forecast[df_forecast.index <= plot_end_time]

    median_col = f"{channel}_q0.5"
    plot_cols_to_check = [median_col]
    for q_low, q_high in quantile_pairs:
        plot_cols_to_check.extend([f"{channel}_q{q_low}", f"{channel}_q{q_high}"])

    # Filter out NaNs specifically for the columns to be plotted
    # Create a copy to avoid SettingWithCopyWarning if df_forecast is a slice
    df_plot = df_forecast.copy()
    cols_to_drop_na = [col for col in plot_cols_to_check if col in df_plot.columns]
    if cols_to_drop_na:
        df_plot.dropna(subset=cols_to_drop_na, inplace=True)

    if df_plot.empty:
        print(f"Warning: No valid data points to plot for {label} after NaN filtering.")
        return

    ax.plot(df_plot.index, df_plot[median_col], label=label, color=color)
    for j, (q_low, q_high) in enumerate(quantile_pairs):
        col_low = f"{channel}_q{q_low}"
        col_high = f"{channel}_q{q_high}"
        if col_low in df_plot.columns and col_high in df_plot.columns:
            ax.fill_between(df_plot.index, df_plot[col_low], df_plot[col_high],
                            alpha=alphas[j], color=color, lw=0)


