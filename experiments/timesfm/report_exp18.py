"""Paired, calendar-block sensitivity tables for exp18 (no new model fits)."""
from __future__ import annotations

import json

import bench
import numpy as np
import pandas as pd
from audit_exp18 import PAIRS, dataset
from exp5_regimes import classify
from exp18_discharge_alone import verdict


def interval(values: pd.Series, months: int = 1):
    """Resample occupied calendar blocks, preserving paired differences and weights.

    Ratio of resampled sums to counts retains equal weighting of windows rather than
    giving a sparse month the same point-estimate weight as a dense month. This is a
    dependence sensitivity, not a claim that neighbouring months are independent.
    """
    values = values.dropna().sort_index()
    keys = ((values.index.year * 12 + values.index.month - 1) // months)
    groups = values.groupby(keys).agg(['sum', 'count'])
    rng = np.random.default_rng(18)
    take = rng.integers(0, len(groups), size=(8000, len(groups)))
    boot = groups['sum'].to_numpy()[take].sum(axis=1) / groups['count'].to_numpy()[take].sum(axis=1)
    return (*np.percentile(boot, [2.5, 97.5]), len(groups))


def stats(scores, candidate, reference, metric):
    values = bench.per_run(scores, metric)[[candidate, reference]].dropna()
    delta = values[candidate] - values[reference]
    base = values[reference].mean()
    lo, hi, blocks = interval(delta)
    qlo, qhi, quarters = interval(delta, 3)
    rng = np.random.default_rng(0)
    d = delta.to_numpy()
    iid = np.percentile(rng.choice(d, size=(8000, len(d))).mean(axis=1), [2.5, 97.5])
    return {'candidate': candidate, 'reference': reference, 'metric': metric, 'n': len(delta),
            'base': base, 'score': values[candidate].mean(), 'delta': delta.mean(),
            'pct': 100*delta.mean()/base, 'lo': lo, 'hi': hi,
            'lo_pct': 100*lo/base, 'hi_pct': 100*hi/base, 'blocks': blocks,
            'quarter_lo_pct': 100*qlo/base, 'quarter_hi_pct': 100*qhi/base,
            'quarters': quarters, 'iid_lo_pct': 100*iid[0]/base, 'iid_hi_pct': 100*iid[1]/base,
            'better_pct': 100*delta.lt(0).mean()}


def md_table(headers, rows):
    return '\n'.join(['| '+' | '.join(headers)+' |', '| '+' | '.join(['---']*len(headers))+' |',
                      *['| '+' | '.join(map(str, row))+' |' for row in rows]])


def pair_table(scores, pairs=PAIRS):
    records, rows = [], []
    for candidate, reference in pairs:
        if not {candidate, reference}.issubset(set(scores.label)):
            continue
        for metric in ('mae', 'crps'):
            s = stats(scores, candidate, reference, metric)
            records.append(s)
            rows.append([candidate+' vs '+reference, metric.upper(), s['n'],
                         f"{s['base']:.4f} → {s['score']:.4f}", f"{s['delta']:+.4f}",
                         f"{s['pct']:+.2f}%", f"[{s['lo_pct']:+.2f}, {s['hi_pct']:+.2f}]",
                         f"[{s['iid_lo_pct']:+.2f}, {s['iid_hi_pct']:+.2f}]"])
    return md_table(['Candidate vs reference', 'Metric', 'Windows', 'Reference → candidate',
                     'Δ °C', 'Δ %', '95% month-block %', '95% IID %'], rows), records


def main():
    df, _ = dataset()
    sections, records = [], {}
    appendix = ['# Experiment 18 — paired tables\n',
                'Generated by `report_exp18.py`. See [the report](REPORT_exp18.md) for interpretation. '
                'Losses cover all 96 hours; paired tables use equally weighted windows. '
                'Negative differences favour the candidate. Both intervals are descriptive 95% intervals; '
                'month blocks address some temporal dependence, IID intervals reproduce the ladder. '
                'Neither adjusts for repeated looks or multiple comparisons.\n']
    titles = {'stage1': 'Stage 1: 100 windows, 1,024 h context',
              'stage2': 'Stage 2: 250 windows, 1,024 h context',
              'stage3': 'Stage 3: 250 windows, 8,760 h context',
              'context_check': 'Context check: 100 stage-1 windows, 8,760 h context'}
    for name in ('stage1', 'stage2', 'stage3', 'context_check'):
        path = bench.CACHE / f'exp18_{name}.csv'
        if name == 'context_check':
            extra = bench.CACHE / 'exp18_context_extra.csv'
            if not extra.exists():
                continue
            scores = pd.read_csv(extra, parse_dates=['reference_time'])
            previous = pd.read_csv(bench.CACHE / 'exp18_stage3.csv', parse_dates=['reference_time'])
            keep = (previous.reference_time.isin(scores.reference_time)
                    & ~previous.label.isin(scores.label))
            scores = pd.concat([scores, previous[keep]])
        else:
            if not path.exists():
                continue
            scores = pd.read_csv(path, parse_dates=['reference_time'])
        sections.append(f'## {name}\n')
        pooled = bench.pool(scores)
        sections.append(md_table(['Variant', 'Windows', 'Hours', 'MAE', 'CRPS'],
                                [[r.label, r.runs, r.n, f'{r.mae:.4f}', f'{r.crps:.4f}']
                                 for r in pooled.itertuples()]))
        table, rec = pair_table(scores)
        appendix.extend([f'## {titles[name]}\n', table])
        sections.append('\nPaired window means (all 96 forecast hours):\n\n'+table)
        records[name] = rec
        if name.startswith('stage'):
            rows = []
            for c, r in PAIRS[:7]:
                if not {c, r}.issubset(set(scores.label)):
                    continue
                rows.append([c+' vs '+r, *[verdict(scores, c, r, m)[0] for m in ('mae','crps')]])
            sections.append('\nOriginal exploratory IID stopping rule:\n\n'+md_table(
                ['Pair', 'MAE', 'CRPS'], rows))
        classified = classify(scores, df.eisbach)
        unique = classified.drop_duplicates('reference_time').sort_values('reference_time')
        cut = unique.abs_swing.quantile(.75)
        movers = classified[classified.abs_swing >= cut]
        mover_times = pd.DatetimeIndex(movers.reference_time.unique()).sort_values()
        overlaps = int((mover_times.to_series().diff() < pd.Timedelta(hours=96)).sum())
        sections.append(f'\nLargest-swing quartile: {len(mover_times)} windows, '
                        f'cutoff |swing| ≥ {cut:.3f} °C; {overlaps} adjacent pairs <96 h apart.\n')
        table, rec = pair_table(movers)
        sections.append(table)
        records[name+'_movers'] = rec
        rows = []
        for regime, group in classified.groupby('regime', observed=True):
            for c, r in [PAIRS[0], PAIRS[1], PAIRS[4], PAIRS[5]]:
                if not {c, r}.issubset(set(group.label)):
                    continue
                for metric in ('mae', 'crps'):
                    s = stats(group, c, r, metric)
                    rows.append([str(regime).replace('\n',' '), c+' vs '+r, metric.upper(),
                                 s['n'], s['blocks'], f"{s['base']:.4f} → {s['score']:.4f}",
                                 f"{s['pct']:+.2f}% [{s['lo_pct']:+.2f}, {s['hi_pct']:+.2f}]"])
        sections.append('\nBy observed swing (descriptive, selected using future truth):\n\n'+md_table(
            ['Regime', 'Pair', 'Metric', 'Windows', 'Months', 'Reference → candidate',
             'Δ % [95% month-block]'], rows))
        rows = []
        for s in records[name]:
            rows.append([s['candidate']+' vs '+s['reference'], s['metric'].upper(), s['quarters'],
                         f"[{s['quarter_lo_pct']:+.2f}, {s['quarter_hi_pct']:+.2f}]"])
        sections.append('\nThree-month block sensitivity:\n\n'+md_table(
            ['Pair', 'Metric', 'Occupied quarters', '95% block %'], rows))
        # Direct interaction: loss change when adding Q with vs without weather.
        rows = []
        for metric in ('mae', 'crps'):
            v = bench.per_run(scores, metric)
            for bare_c, bare_r, wet_c, wet_r in [
                ('Q','nur Eisbach','Wetter + Q','Wetter'),
                ('T+Q','T','Wetter + T+Q','Wetter + T')]:
                cols = [bare_c,bare_r,wet_c,wet_r]
                if not set(cols).issubset(v.columns):
                    continue
                z = v[cols].dropna()
                d = (z[wet_c]-z[wet_r]) - (z[bare_c]-z[bare_r])
                lo, hi, blocks = interval(d)
                relative = 100*((z[wet_c]-z[wet_r])/z[wet_r].mean()
                                - (z[bare_c]-z[bare_r])/z[bare_r].mean())
                rlo, rhi, _ = interval(relative)
                rows.append([bare_c+' / '+wet_c, metric.upper(), f'{d.mean():+.4f}',
                             f'[{lo:+.4f}, {hi:+.4f}]',
                             f'{relative.mean():+.2f} [{rlo:+.2f}, {rhi:+.2f}]', blocks])
        if rows:
            sections.append('\nQ×weather interaction: (with-weather Δ loss) − (bare Δ loss); '
                            'positive means attenuation of Q benefit.\n\n'+md_table(
                                ['Pair', 'Metric', 'ΔΔ °C', '95% month-block °C',
                                 'Relative attenuation pp [95% CI]', 'Months'], rows))
        context = 1024 if name in ('stage1', 'stage2') else 8760
        good = []
        for a in unique.reference_time:
            pos = df.index.get_loc(a)
            if df['q_toelz_kw'].iloc[pos-context+1:pos+1].isna().mean() <= .05:
                good.append(a)
        for sensitivity, selected in [
            ('q_missing_at_most_5pct', scores[scores.reference_time.isin(good)]),
            ('exclude_2026', scores[scores.reference_time.dt.year != 2026]),
        ]:
            table, rec = pair_table(selected, [PAIRS[i] for i in (0, 1, 4, 5)])
            records[name+'_'+sensitivity] = rec
            sections.append(f'\nSensitivity: {sensitivity}\n\n'+table)
        if name == 'stage3':
            for horizon in (6, 24):
                table, rec = pair_table(scores[scores.lead_hi <= horizon],
                                        [PAIRS[i] for i in (0, 1, 4, 5)])
                records[f'{name}_first_{horizon}h'] = rec
                sections.append(f'\nFirst {horizon} forecast hours only:\n\n'+table)
            rows = []
            for c, r in [PAIRS[i] for i in (0, 1, 4, 5)]:
                if not {c, r}.issubset(set(scores.label)):
                    continue
                for metric in ('mae', 'crps'):
                    v = bench.per_run(scores, metric)[[c, r]].dropna()
                    effects = {}
                    for year in sorted(set(v.index.year)):
                        z = v[v.index.year != year]
                        effects[year] = 100*(z[c]-z[r]).mean()/z[r].mean()
                    rows.append([c+' vs '+r, metric.upper(),
                                 f'{min(effects.values()):+.2f} to {max(effects.values()):+.2f}',
                                 '; '.join(f'{y}: {p:+.2f}' for y, p in effects.items())])
            sections.append('\nLeave-one-year-out effect sensitivity (point estimates only):\n\n'+md_table(
                ['Pair', 'Metric', 'Δ % range', 'Excluded year: Δ %'], rows))
    (bench.CACHE / 'exp18_tables.md').write_text('\n\n'.join(sections)+'\n')
    (bench.CACHE / 'exp18_summary.json').write_text(json.dumps(records, indent=2))
    (bench.REPO / 'experiments/timesfm/REPORT_exp18_tables.md').write_text('\n\n'.join(appendix)+'\n')


if __name__ == '__main__':
    main()
