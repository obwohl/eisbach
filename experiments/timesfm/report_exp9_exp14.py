"""Rebuild paired report tables from the local, completed experiment checkpoints."""
import json
import logging
from pathlib import Path

import bench
import numpy as np
import pandas as pd
from checkpoint import resume

OUT = Path(__file__).with_name('REPORT_exp9_exp14.md')


def display(value):
    """Correct geographic descriptions without rewriting legacy checkpoint keys."""
    return (value.replace('Rißbach-Düker (Ableitung)', 'Rißbachdüker / Isar')
            .replace('Sylvenstein Zufluss', 'Sylvenstein / Isar (below reservoir)')
            .replace('Loisach-Beuerberg-Kanal', 'Beuerberg virtual: Loisach with canal'))


def table(headers, rows):
    return '\n'.join(['| ' + ' | '.join(headers) + ' |',
                      '| ' + ' | '.join(['---'] * len(headers)) + ' |',
                      *['| ' + ' | '.join(display(str(value)) for value in row) + ' |'
                        for row in rows]]) + '\n'


def paired_table(scores, reference, labels=None):
    candidates = [label for label in scores.label.unique() if label != reference]
    # Reuse the same bootstrap draws across candidates; identical effects then have
    # identical intervals instead of differing due only to Monte Carlo noise.
    stats = {m: pd.concat([bench.paired(scores[scores.label.isin([reference, label])],
                                      reference, metric=m) for label in candidates])
             .set_index('label') for m in ('mae', 'crps')}
    pooled = bench.pool(scores).set_index('label')
    rows = []
    labels = list(stats['mae'].index) if labels is None else labels
    for label in labels:
        row = [label, int(pooled.loc[label, 'runs'])]
        for m in ('mae', 'crps'):
            r = stats[m].loc[label]
            base = bench.per_run(scores, m)[reference].mean()
            row += [f'{pooled.loc[label, m]:.6f}',
                    f'{r.pct:+.3f}% [{100*r.ci_lo/base:+.3f}, {100*r.ci_hi/base:+.3f}]']
        rows.append(row)
    base = pooled.loc[reference]
    return (f'Reference: **{reference}**; MAE {base.mae:.6f} °C, CRPS {base.crps:.6f} °C.\n\n'
            + table(['Variant', 'Windows', 'MAE °C', 'Δ MAE % [95% CI]',
                     'CRPS °C', 'Δ CRPS % [95% CI]'], rows))


def monthly_table(scores, reference, labels):
    rows = []
    for label in labels:
        row = [label]
        for metric in ('mae', 'crps'):
            values = bench.per_run(scores, metric)
            delta = values[label] - values[reference]
            month = pd.to_datetime(delta.index, utc=True).strftime('%Y-%m')
            grouped = delta.groupby(month).agg(['sum', 'count'])
            rng = np.random.default_rng(0)
            ix = rng.integers(0, len(grouped), size=(8000, len(grouped)))
            boot = grouped['sum'].to_numpy()[ix].sum(axis=1) / grouped['count'].to_numpy()[ix].sum(axis=1)
            lo, hi = 100 * np.percentile(boot, [2.5, 97.5]) / values[reference].mean()
            row.append(f'[{lo:+.3f}, {hi:+.3f}]')
        rows.append(row)
    return table(['Variant vs ' + reference, 'MAE % monthly-block CI', 'CRPS % monthly-block CI'], rows)


def load_scores(name):
    path = bench.CACHE / f'{name}.csv'
    manifest = json.loads(path.with_suffix('.json').read_text())
    labels = [variant[0] for variant in manifest['variants']]
    scores = pd.DataFrame(resume(path, labels, manifest['anchors']))
    if scores.empty or set(scores.label) != set(labels):
        raise ValueError(f'{name}: not all planned variants have finished')
    return scores


def main():
    scores = {name: load_scores(name)
              for name in ['exp9_targets', 'exp9_confirm', 'exp14_branches', 'exp14_confirm']}
    parts = ['# Paired tables: exp9 and exp14\n',
             'Generated by `report_exp9_exp14.py`. Negative changes favour the candidate. '
             'Intervals are paired 95% bootstrap intervals (8,000 shared draws); percentages and '
             'intervals use the mean per-window reference score as denominator. Absolute '
             'scores pool observed hours. CRPS is integrated over deciles 0.1–0.9.\n']
    for name, title, ref in [('exp9_targets', 'exp9 screen, 1024 h', 'upstream as covariates'),
                             ('exp9_confirm', 'exp9 confirmation, 8760 h', 'upstream as covariates'),
                             ('exp14_branches', 'exp14 screen, 1024 h', 'weather only'),
                             ('exp14_confirm', 'exp14 confirmation, 8760 h', 'weather only')]:
        s = scores[name]
        parts += [f'## {title}\n', paired_table(s, ref)]
        if name.startswith('exp9'):
            parts += ['### One-gauge framing comparison\n',
                      paired_table(s, 'Bad Tölz only, as covariate', ['Bad Tölz only, as target'])]
    full = scores['exp14_confirm']
    incremental = [x for x in full.label.unique() if x.startswith('Bad Tölz T + ')]
    parts += ['## Incremental branch value at 8760 h\n', paired_table(full, 'Bad Tölz T', incremental),
              '## Dependence sensitivity\n',
              'Resample calendar months with all their windows together; this accommodates '
              'within-month dependence, but is not an independent temporal holdout.\n',
              monthly_table(full, 'weather only',
                            [label for label in full.label.unique() if label != 'weather only']),
              monthly_table(full, 'Bad Tölz T', incremental),
              monthly_table(scores['exp9_confirm'], 'upstream as covariates',
                            ['Bad Tölz only, as covariate', 'upstream as targets and covariates'])]
    for prefix, screen in [('exp9', 'exp9_targets'), ('exp14', 'exp14_branches')]:
        a, b = scores[screen], scores[prefix + '_confirm']
        common = sorted(set(a.label) & set(b.label))
        rows = []
        for metric in ('mae', 'crps'):
            av, bv = bench.per_run(a, metric)[common].mean(), bench.per_run(b, metric)[common].mean()
            ar, br = av.rank(method='min'), bv.rank(method='min')
            for label in common:
                rows.append([metric.upper(), label, int(ar[label]), int(br[label]),
                             f'{av[label]:.6f}', f'{bv[label]:.6f}'])
        parts += [f'## {prefix}: ranking among jointly evaluated variants\n',
                  table(['Metric', 'Variant', 'Screen rank', 'Full rank', 'Screen score', 'Full score'],
                        rows)]
    rows = []
    for year in sorted(full.reference_time.dt.year.unique()):
        omitted = full[full.reference_time.dt.year != year]
        values = {metric: bench.per_run(omitted, metric) for metric in ('mae', 'crps')}
        for label in incremental:
            changes = [100 * (values[m][label] - values[m]['Bad Tölz T']).mean()
                       / values[m]['Bad Tölz T'].mean() for m in ('mae', 'crps')]
            rows.append([year, len(values['mae']), label, *[f'{v:+.3f}%' for v in changes]])
    parts += ['## exp14 leave-one-year-out sensitivity\n',
              'Post-hoc influence diagnostic, not a new holdout or an altered primary sample.\n',
              table(['Omitted year', 'Remaining windows', 'Addition to Bad Tölz',
                     'Δ MAE', 'Δ CRPS'], rows)]
    parts += ['## exp14 confirmation by calendar year\n']
    for year, group in full.groupby(full.reference_time.dt.year):
        parts += [f'### {year}\n', paired_table(group, 'Bad Tölz T', incremental)]
    for name, s in scores.items():
        n = s.groupby('label').reference_time.nunique()
        if len(n.unique()) != 1 or not np.isfinite(s[['mae', 'crps', 'rmse']]).all().all():
            raise ValueError(f'Invalid or unpaired scores: {name}')
    marker = '\n<!-- generated tables -->\n'
    narrative = OUT.read_text().split(marker)[0] if OUT.exists() else ''
    OUT.write_text(narrative + marker + '\n'.join(parts))
    logging.getLogger(__name__).info('Wrote %s', OUT)


if __name__ == '__main__':
    logging.basicConfig(level=logging.INFO)
    main()
